#!/bin/bash
# build_tp.sh [name ...]: Qualcomm's techpack driver repos (secure world, synx, fences, MMRM, DSP,
# display, GPU, video ...) built for sun as external modules against out/gki and the SoC build, in
# dependency order, each one's Module.symvers handed to the ones after it. Adapted from the
# reference's k618_tp.sh (kalama) to sun.
#
# Sources: OnePlus' SM8850 release (src/mods8850), copied fresh into src/vendor/qcom/opensource on
# every run and fixed there (the reference's generic 6.12 -> 6.18 fixes, scripts/tp_fix.py, and its
# API sweeps, k618_fix618.py). Modules collected in out/tpmods, a log per repo in out/tp-log.
set -e
. "$(dirname "$0")/env.sh"
TP=$ROOT/src/vendor/qcom/opensource
SRC=$ROOT/src/mods8850/vendor/qcom/opensource
OUTM=$ROOT/out/tpmods
LOG=$ROOT/out/tp-log
[ -f "$S/Module.symvers" ] && [ -f "$S/gen/autoconf_vendor.h" ] || { echo "build_tp: build the SoC modules first"; exit 1; }

REPOS_ALL="securemsm-kernel synx-kernel mm-drivers mmrm-driver dsp-kernel display-drivers graphics-kernel"
mkdir -p "$TP" "$OUTM" "$LOG"
for t in $REPOS_ALL; do
	rsync -a --delete "$SRC/$t/" "$TP/$t/"
done
# Nine trace headers reach a neighbour repo as ../../../../vendor/qcom/opensource/... from the
# kernel's include/trace (Qualcomm's layout: kernel_platform/common next to vendor/). Here the
# kernel is src/common, so the techpacks are one level less up: src/vendor/qcom/opensource.
grep -rlZ '\.\./\.\./\.\./\.\./vendor/qcom/opensource' "$TP" | xargs -0 -r \
	sed -i 's#\.\./\.\./\.\./\.\./vendor/qcom/opensource#../../../vendor/qcom/opensource#g'
python3 -I "$ROOT/scripts/tp_fix.py" "$REF" "$TP"
python3 -I "$ROOT/scripts/tp_op13_fix.py" "$TP"
for d in "$TP"/*; do
	python3 -I "$REF/k618_fix618.py" "$d" | grep -v 'k618_fix618: 0 files changed' | sed "s|^|$(basename "$d"): |" || true
done

# KGSL takes its chipset options from Kleaf (config/sun_perf_gpuconf); for `make M=` they become
# make variables and, for the C code, a forced-include header
GPUCONF=$TP/graphics-kernel/config/sun_perf_gpuconf
# ... less those the OnePlus 13's own sun_perf_gpuconf turns off ("# CONFIG_X=y" there): its KGSL
# allocates from KGSL's page pools, not through shmem (QCOM_KGSL_USE_SHMEM, and PROCESS_RECLAIM on
# top of it). Through shmem every GPU buffer is a shmem file's pages, charged to the allocating
# app's memory cgroup and the shmem accounting: ColorOS' per-app limits refused the large ones
# ("kgsl_sharedmem_alloc() failed" for 6-18 MB Vulkan images: black screenshots, Telegram's and
# the AOD's artifacts on ColorOS 17)
OP13GPU=$ROOT/src/mods8750/vendor/qcom/opensource/graphics-kernel/config/sun_perf_gpuconf
GPUOFF=$(sed -n -E 's/^#[[:space:]]*(CONFIG_[A-Z0-9_]+)=y.*/\1/p' "$OP13GPU" 2>/dev/null | tr '\n' ' ')
gpuconf() {
	grep -E '^CONFIG_[A-Z0-9_]+=' "$GPUCONF" | while IFS='=' read -r k v; do
		case " $GPUOFF " in *" $k "*) ;; *) echo "$k=$v" ;; esac
	done
}
echo "build_tp: KGSL options the OnePlus 13 turns off, left out: ${GPUOFF:-none}"
GPUVARS=$(gpuconf | grep -v '"' | tr '\n' ' ')
{
	echo "/* generated by scripts/build_tp.sh from config/sun_perf_gpuconf */"
	gpuconf | while IFS='=' read -r k v; do
		case "$v" in
			y) echo "#define $k 1" ;;
			m) echo "#define ${k}_MODULE 1" ;;
			*) echo "#define $k $v" ;;
		esac
	done
} > "$TP/graphics-kernel/gki_sun_gpuconf.h"

# headers the multimedia repos take from one another (Kleaf passes them as exported includes)
MMINC="%T/synx-kernel/msm/synx %T/synx-kernel/include %T/synx-kernel/include/uapi
       %T/synx-kernel/include/uapi/synx/media %T/mm-drivers/hw_fence/include
       %T/mm-drivers/hfi_core/inc %T/mm-drivers/msm_ext_display/include
       %T/mm-drivers/sync_fence/include %T/securemsm-kernel/hdcp
       %T/securemsm-kernel %T/securemsm-kernel/include %T/securemsm-kernel/include/linux
       %T/dsp-kernel/include"

# name | directory (M=) | make variables | extra include dirs | extra flags
REPOS=(
	"securemsm|securemsm-kernel|SSG_MODULE_ROOT=%D CONFIG_DISABLE_TEST_MODULES=y|%T/securemsm-kernel/include %T/securemsm-kernel/include/linux|"
	"synx|synx-kernel|SYNX_ROOT=%D|"
	"sync_fence|mm-drivers/sync_fence|SYNC_FENCE_ROOT=%P/|"
	"msm_ext_display|mm-drivers/msm_ext_display|MSM_EXT_DISPLAY_ROOT=%P/|"
	"hw_fence|mm-drivers/hw_fence|MSM_HW_FENCE_ROOT=%P/|%T/synx-kernel/msm/synx %T/synx-kernel/include %T/synx-kernel/include/uapi %T/synx-kernel/include/uapi/synx/media"
	"mmrm|mmrm-driver|MMRM_ROOT=%D|"
	"dsp|dsp-kernel|DSP_ROOT=%D|"
	"hfi_core|mm-drivers/hfi_core|MSM_HFI_CORE_ROOT=%P/|%M|"
	"display|display-drivers|DISPLAY_ROOT=%D CONFIG_DRM_MSM=m|%M|-include %T/k618_oplus_stub.h"
	"graphics|graphics-kernel|KGSL_PATH=%D $GPUVARS CONFIG_ARM_SMMU=y|%M %C/drivers/devfreq|-include %T/graphics-kernel/gki_sun_gpuconf.h -DCONFIG_ARM_SMMU=1"
	# video: this release has no sun platform sources (driver/platform/sun) -- they are in the
	# OnePlus 13's own 6.6 tree; left out until they are brought over (not needed to boot)
)

# The vendor configuration as the techpacks see it (env.sh)
TPCONF=$ROOT/out/tp-autoconf.h
soc_autoconf "$TPCONF" techpacks

SYMS=$S/Module.symvers
addsym() { case " $SYMS " in *" $1 "*) ;; *) SYMS="$SYMS $1";; esac; }
rm -f "$LOG"/*.symvers "$OUTM"/*.ko
ok=0; bad=0; failed=
for entry in "${REPOS[@]}"; do
	IFS='|' read -r name dir vars incs defs <<< "$entry"
	if [ $# -gt 0 ]; then
		case " $* " in *" $name "*) ;; *) continue;; esac
	fi
	D=$TP/$dir
	incs=${incs//%M/$MMINC}
	for v in vars incs defs; do
		eval "$v=\${$v//%D/\$D}; $v=\${$v//%P/\$(dirname \$D)}; $v=\${$v//%T/\$TP}; $v=\${$v//%C/\$C}"
	done
	EI=; for i in $incs; do EI="$EI -I$i"; done
	start=$(date +%s)
	set +e
	# CONFIG_ARCH_SUN: the chipset each Kbuild keys its configuration off. NOSTDINC_FLAGS puts the
	# SoC tree's headers before the kernel's own, as the SoC build itself does
	# shellcheck disable=SC2086
	"${KMAKE[@]}" M="$D" modules -k -j"$J" KERNEL_SRC="$C" KERNEL_ROOT="$C" \
		CONFIG_ARCH_SUN=y KBUILD_EXTRA_SYMBOLS="$SYMS" \
		NOSTDINC_FLAGS="-nostdinc -I$S/include -I$S/include/uapi$EI" \
		KCFLAGS="-Wno-error -include $TPCONF $defs" $vars > "$LOG/$name.log" 2>&1
	rc=$?
	set -e
	n=$(find "$D" -name '*.ko' | wc -l)
	echo "build_tp: $name: make exit $rc in $(( $(date +%s) - start )) s, $n modules"
	if [ $rc -ne 0 ]; then
		bad=$((bad + 1)); failed="$failed $name"
		grep -E ': (fatal )?error: |^ERROR: modpost|No rule to make target' "$LOG/$name.log" \
			| sed -E "s|$TP/||" | awk -F: '!seen[$1$2]++' | head -40 || true
		continue
	fi
	ok=$((ok + 1))
	[ -f "$D/Module.symvers" ] && cp "$D/Module.symvers" "$LOG/$name.symvers" && addsym "$LOG/$name.symvers"
	find "$D" -name '*.ko' -exec cp {} "$OUTM/" \;
done
echo "build_tp: built $ok, failed $bad${failed:+ ($failed )}; modules in out/tpmods: $(ls "$OUTM"/*.ko 2> /dev/null | wc -l)"
[ "$bad" -eq 0 ]
